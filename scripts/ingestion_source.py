"""
scripts/ingestion_source.py
IngestionSource seam (A8, Appendix 4) -- the E1 provider slot behind
scripts/ingest.py, resolved by `ingestion.source` in config/flags.toml.

Strategy §6 / Appendix 6 names a live Beckn/ONDC-protocol data source
(`ingestion.source = "beckn"`) as deferred scope: "Every store is populated
through an ingestion boundary rather than by hand, so a live Beckn-protocol
source would be a new ingestion implementation, not a change to the query
path." `LocalFileSource` is the one shipped implementation, reading the
static fixtures/documents/ corpus this build ships with.

This module is imported only by scripts/ingest.py -- an operator-run,
host-side job (A1: "never by the orchestrator, never by an agent"), so it
lives in scripts/, not orchestrator/, matching where its actual consumer
and dispatch point are. It is deliberately NOT wired into orchestrator's or
mcp's own config_loader/registry patterns, since neither service may ever
invoke ingestion (E1-V7).
"""

from __future__ import annotations

import os
import tomllib
from pathlib import Path
from typing import Protocol

REPO_ROOT = Path(__file__).resolve().parent.parent


class IngestionSource(Protocol):
    """Resolves where the document corpus to ingest comes from."""

    def manifest_path(self) -> Path:
        """Path to the manifest.json listing documents to ingest."""
        ...

    def documents_dir(self) -> Path:
        """Directory containing the documents the manifest references."""
        ...


class LocalFileSource:
    """
    Shipped implementation. Reads the static fixtures/documents/ corpus
    generated by scripts/gen_document_corpus.py -- unchanged behavior from
    before this seam existed; wiring it in does not alter what ingest.py
    ingests by default.
    """

    def __init__(self, documents_dir: Path | None = None) -> None:
        self._dir = documents_dir or (REPO_ROOT / "fixtures" / "documents")

    def manifest_path(self) -> Path:
        return self._dir / "manifest.json"

    def documents_dir(self) -> Path:
        return self._dir


def _flags_ingestion_source() -> str:
    config_dir = Path(os.environ["CONFIG_DIR"]) if os.environ.get("CONFIG_DIR") else REPO_ROOT / "config"
    with open(config_dir / "flags.toml", "rb") as f:
        data = tomllib.load(f)
    return str(data.get("ingestion", {}).get("source", "local"))


def get_ingestion_source() -> IngestionSource:
    """
    Resolves by name from config/flags.toml's `ingestion.source` (A8).
    Unresolvable name = failure, never a silent default -- same rule every
    other provider resolver in this build follows (get_language_normalizer,
    get_schema_retriever, get_spatial_resolver, get_scorer).
    """
    provider = _flags_ingestion_source()
    if provider == "local":
        return LocalFileSource()
    raise RuntimeError(
        f"Unknown ingestion.source {provider!r}. Valid values: 'local'. "
        "('beckn' is Strategy §6 deferred scope -- Appendix 4 names the flag "
        "value but no implementation is built; see docs/limitations.md.)"
    )
