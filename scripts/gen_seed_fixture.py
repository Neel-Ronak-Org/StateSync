FULFILLMENT_STATUSES = ["pending", "in_transit", "delivered", "failed", "returned"]
PARTICIPANT_TYPES_BUYER = ["buyer_app", "gateway"]


def _digipin_placeholder(lat: float, lon: float) -> str:
    """
    Deterministic 10-char Digipin-style code from lat/lon.
    Real values generated by gen_digipin_fixture.py with the pinned library.
    Format: AAABBBCCCC (no separators, canonical form per A5 schema comment).
    """
    charset = "23456789ABCDEFGHJKLMNPQRSTUVWXYZ"
    combined = abs(int(lat * 1000) * 100000 + int(lon * 1000))
    code = ""
    for _ in range(10):
        code = charset[combined % len(charset)] + code
        combined //= len(charset)
    return code


def _ts(days_ago: float, hour_offset: float = 0.0) -> str:
    base = datetime(2026, 7, 15, 10, 0, 0, tzinfo=timezone.utc)
    dt = base - timedelta(days=days_ago, hours=hour_offset)
    return dt.isoformat()


def _id(prefix: str, n: int) -> str:
    return f"{prefix}{n:04d}"


def generate() -> dict:
    # ── Locations: 50 (>= 40 required) ───────────────────────────────────────
    locations = []
    loc_idx = 1
    for city, city_local, state, lat, lon, pincode, gst in CITY_DATA:
        # 2-3 locations per city
        for offset_idx in range(rng.randint(2, 3)):
            lat_jitter = lat + rng.uniform(-0.05, 0.05)
            lon_jitter = lon + rng.uniform(-0.05, 0.05)
            locations.append({
                "location_id": _id("loc_", loc_idx),
                "digipin": _digipin_placeholder(lat_jitter, lon_jitter),
                "lat": round(lat_jitter, 6),
                "lon": round(lon_jitter, 6),
                "city": city,
                "city_local": city_local,
                "state": state,
                "pincode": pincode,
            })
            loc_idx += 1
            if loc_idx > 50:
                break
        if loc_idx > 50:
            break

    location_ids = [l["location_id"] for l in locations]

    # ── Buyer apps (network_participants of type buyer_app/gateway) ───────────
    buyer_apps = []
    for i in range(1, 6):
        buyer_apps.append({
            "participant_id": f"BA{i:03d}",
            "legal_name": f"BuyerApp {i} Pvt Ltd",
            "participant_type": "buyer_app",
            "onboarded_on": "2025-01-15",
            "gst_state_code": rng.choice([gst for *_, gst in CITY_DATA]),
        })

    # ── Sellers: 30 (>= 25 required) ─────────────────────────────────────────
    seller_participants = []
    sellers = []
    for i in range(1, 31):
        city_row = CITY_DATA[rng.randint(0, len(CITY_DATA) - 1)]
        city, city_local, state, lat, lon, pincode, gst = city_row
        pid = f"S{i:03d}"
        seller_participants.append({
            "participant_id": pid,
            "legal_name": f"Seller {i} Trading Co",
            "participant_type": "seller",
            "onboarded_on": _ts(rng.randint(180, 365))[:10],
            "gst_state_code": gst,
        })
        sellers.append({
            "seller_id": pid,
            "display_name": f"Seller Store {i}",
            "display_name_local": f"विक्रेता {i}",
            "category": rng.choice(CATEGORIES),
            "location_id": rng.choice(location_ids),
            "contracted_sla_hours": rng.choice([24, 36, 48, 72]),
        })
    seller_ids = [s["seller_id"] for s in sellers]

    # ── Logistics providers: 10 (>= 8 required) ──────────────────────────────
    lp_participants = []
    logistics_providers = []
    for i in range(1, 11):
        pid = f"LP{i:03d}"
        lp_participants.append({
            "participant_id": pid,
            "legal_name": f"Logistics Co {i}",
            "participant_type": "logistics",
            "onboarded_on": _ts(rng.randint(200, 400))[:10],
            "gst_state_code": rng.choice([gst for *_, gst in CITY_DATA]),
        })
        logistics_providers.append({
            "provider_id": pid,
            "display_name": f"FastShip {i}",
            "hub_location_id": rng.choice(location_ids),
            "b2b_enabled": rng.random() > 0.5,
        })
    lp_ids = [lp["provider_id"] for lp in logistics_providers]

    # ── Catalog items: 100 items across sellers ───────────────────────────────
    catalog_items = []
    for i in range(1, 101):
        seller = rng.choice(seller_ids)
        cat = rng.choice(CATEGORIES)
        catalog_items.append({
            "item_id": _id("ITM", i),
            "seller_id": seller,
            "title": f"{cat.title()} Product {i}",
            "title_local": f"उत्पाद {i}",
            "category": cat,
            "unit_price": round(rng.uniform(50, 5000), 2),
        })
    item_ids = [it["item_id"] for it in catalog_items]
    buyer_ids = [b["participant_id"] for b in buyer_apps]

    # ── Orders: 550 (>= 500 required) ────────────────────────────────────────
    orders = []
    for i in range(1, 551):
        seller = rng.choice(seller_ids)
        days_ago = rng.uniform(0, 90)
        orders.append({
            "order_id": _id("ORD", i),
            "buyer_app_id": rng.choice(buyer_ids),
            "seller_id": seller,
            "placed_at": _ts(days_ago),
            "order_channel": rng.choice(ORDER_CHANNELS),
            "ship_to_location_id": rng.choice(location_ids),
            "order_value": round(rng.uniform(100, 50000), 2),
        })
    order_ids = [o["order_id"] for o in orders]

    # ── Order items: 1-3 items per order ──────────────────────────────────────
    order_items = []
    for oid in order_ids:
        n_items = rng.randint(1, 3)
        chosen_items = rng.sample(item_ids, min(n_items, len(item_ids)))
        for iid in chosen_items:
            qty = rng.randint(1, 5)
            # find unit_price
            price = next(it["unit_price"] for it in catalog_items if it["item_id"] == iid)
            order_items.append({
                "order_id": oid,
                "item_id": iid,
                "quantity": qty,
                "line_value": round(price * qty, 2),
            })

    # ── Fulfillments: 550 (>= 500 required) ──────────────────────────────────
    fulfillments = []
    for i, oid in enumerate(order_ids[:550], 1):
        order = orders[i - 1]
        placed_dt = datetime.fromisoformat(order["placed_at"])
        promised_dt = placed_dt + timedelta(hours=rng.choice([24, 36, 48, 72]))
        status = rng.choices(
            FULFILLMENT_STATUSES,
            weights=[5, 15, 60, 10, 10],
        )[0]
        delivered_at = None
        if status == "delivered":
            delivery_offset = rng.uniform(-12, 36)  # can be early or late
            delivered_dt = promised_dt + timedelta(hours=delivery_offset)
            if delivered_dt > datetime.now(tz=timezone.utc):
                delivered_at = None
                status = "in_transit"
            else:
                delivered_at = delivered_dt.isoformat()

        fulfillments.append({
            "fulfillment_id": _id("FUL", i),
            "order_id": oid,
            "provider_id": rng.choice(lp_ids),
            "promised_at": promised_dt.isoformat(),
            "delivered_at": delivered_at,
            "status": status,
            "attempt_count": rng.randint(1, 3),
        })
    fulfillment_ids = [f["fulfillment_id"] for f in fulfillments]

    # ── Delivery events: 1800 (>= 1500 required) ─────────────────────────────
    delivery_events = []
    for fid in fulfillment_ids:
        n_events = rng.randint(2, 5)
        for j in range(n_events):
            delivery_events.append({
                "fulfillment_id": fid,
                "occurred_at": _ts(rng.uniform(0, 60), hour_offset=rng.uniform(0, 23)),
                "event_type": rng.choice(EVENT_TYPES),
                "location_id": rng.choice(location_ids) if rng.random() > 0.3 else None,
                "note": rng.choice([
                    None,
                    "Package received at hub",
                    "Out for delivery",
                    "Delivery attempted - recipient unavailable",
                    "Package delivered at door",
                    "Returned to sender",
                    # Adversarial payload test surface (spec mentions free text)
                    "Normal delivery note",
                ]),
            })

    # ── Disputes: 80 (>= 60 required) ────────────────────────────────────────
    disputes = []
    chosen_orders_for_disputes = rng.sample(order_ids, min(80, len(order_ids)))
    for i, oid in enumerate(chosen_orders_for_disputes, 1):
        raised_days_ago = rng.uniform(1, 60)
        resolved = rng.random() > 0.4
        disputes.append({
            "dispute_id": _id("DIS", i),
            "order_id": oid,
            "raised_at": _ts(raised_days_ago),
            "category": rng.choice(DISPUTE_CATEGORIES),
            "resolved_at": _ts(raised_days_ago - rng.uniform(1, 7)) if resolved else None,
            "narrative": rng.choice([
                "Customer reported item not delivered.",
                "Wrong product received.",
                "Item damaged in transit.",
                "Refund not processed within SLA.",
                "Delivery partner did not attempt delivery.",
                None,
            ]),
        })

    # ── Assemble fixture ──────────────────────────────────────────────────────
    all_participants = buyer_apps + seller_participants + lp_participants

    fixture = {
        "version": 1,
        "tenant_id": "t_capstone_default",
        "generated_at": "2026-08-12T00:00:00Z",
        "generated_by": "scripts/gen_seed_fixture.py",
        "rng_seed": RNG_SEED,
        "counts": {
            "locations": len(locations),
            "network_participants": len(all_participants),
            "sellers": len(sellers),
            "logistics_providers": len(logistics_providers),
            "catalog_items": len(catalog_items),
            "orders": len(orders),
            "order_items": len(order_items),
            "fulfillments": len(fulfillments),
            "delivery_events": len(delivery_events),
            "disputes": len(disputes),
        },
        "locations": locations,
        "network_participants": all_participants,
        "sellers": sellers,
        "logistics_providers": logistics_providers,
        "catalog_items": catalog_items,
        "orders": orders,
        "order_items": order_items,
        "fulfillments": fulfillments,
        "delivery_events": delivery_events,
        "disputes": disputes,
    }

    # Verify minimums
    assert len(locations) >= 40, f"Need >= 40 locations, got {len(locations)}"
    assert len(sellers) >= 25, f"Need >= 25 sellers, got {len(sellers)}"
    assert len(logistics_providers) >= 8, f"Need >= 8 logistics_providers"
    assert len(orders) >= 500, f"Need >= 500 orders"
    assert len(fulfillments) >= 500, f"Need >= 500 fulfillments"
    assert len(delivery_events) >= 1500, f"Need >= 1500 delivery_events"
    assert len(disputes) >= 60, f"Need >= 60 disputes"

    return fixture


if __name__ == "__main__":
    out_path = Path(__file__).parent.parent / "fixtures" / "ondc_seed.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)

    fixture = generate()
    counts = fixture["counts"]

    print("Generated fixture counts:")
    for k, v in counts.items():
        print(f"  {k:<30} {v}")

    out_path.write_text(json.dumps(fixture, indent=2, default=str))
    print(f"\nWritten to: {out_path}")
    print("Freeze this file — do not re-generate unless explicitly instructed (Appendix 2.1).")
