"""
scripts/gen_seed_fixture.py
Generates fixtures/ondc_seed.json with all minimum counts required by
Deliverable 4:
  >= 40 locations, >= 25 sellers, >= 8 logistics providers,
  >= 500 orders, >= 500 fulfillments, >= 1500 delivery events, >= 60 disputes.

Run once and the output is frozen (Appendix 2.1 spec).
Digipin values are generated by the pinned 'digipin' library from each row's
lat/lon at fixture-build time (Appendix 2.1), then frozen.
"""

from __future__ import annotations

