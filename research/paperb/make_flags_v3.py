#!/usr/bin/env python3
"""
research/paperb/make_flags_v3.py
Part D v3's flags files (docs/specs/routing_docs_fixes.md §7), generated from the committed
config/flags.toml so they never drift from it: the same file with only Part D's hosts (the
openai_compat provider and Cheaper Inference roles, as in flags_partd_{dense,bge}.toml) and the
Part D switches set. Rerun after any change to config/flags.toml.

  flags_partd_v3_off.toml   every v3 fix at its shipped value (the "as shipped" arm on Part D's hosts)
  flags_partd_v3_on.toml    every v3 fix on; the front door, when T4a is merged, as `front_door` below
  (re-ranking is the shipped "bge" in both; the arms that vary it pass it per request or get their own file)

    /opt/anaconda3/bin/python3 research/paperb/make_flags_v3.py [--front-door off|llm|jev] [--debug-hooks]
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "config" / "flags.toml"
OUT = REPO / "research" / "paperb"
ROLES = {"supervisor": "cheaperinference:qwen-3-8-27b", "sql": "cheaperinference:gpt-oss-120b",
         "synthesizer": "cheaperinference:gpt-oss-120b", "memory_summarizer": "cheaperinference:qwen-3-8-27b",
         "normalizer": "cheaperinference:qwen-3-8-27b", "decomposer": "cheaperinference:qwen-3-8-27b",
         "rewriter": "cheaperinference:qwen-3-8-27b"}
FIXES_ON = {"sql_no_data": "on", "plain_failures": "on", "route_recovery": "on",
            "passage_order": "relevance", "passage_titles": "on", "rerank_titles": "on"}


def set_value(text: str, key: str, value: str, section: str | None = None) -> str:
    """Replace `key = "..."` keeping the line's comment. Without `section` the key must exist exactly
    once in the file; with it, exactly once inside that [section] (up to the next header)."""
    pattern = re.compile(rf'^({re.escape(key)}\s*=\s*)"[^"]*"', re.M)
    if section is None:
        if len(pattern.findall(text)) != 1:
            raise SystemExit(f"{key}: expected exactly one line in {SRC}")
        return pattern.sub(lambda m: f'{m.group(1)}"{value}"', text)
    head = re.search(rf"^\[{re.escape(section)}\][^\n]*\n", text, re.M)
    if head is None:
        raise SystemExit(f"[{section}] not found in {SRC}")
    nxt = re.search(r"^\[", text[head.end():], re.M)
    end = head.end() + (nxt.start() if nxt else len(text) - head.end())
    body = text[head.end():end]
    if len(pattern.findall(body)) != 1:
        raise SystemExit(f"{key}: expected exactly one line in [{section}] of {SRC}")
    return text[:head.end()] + pattern.sub(lambda m: f'{m.group(1)}"{value}"', body) + text[end:]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--front-door", choices=["off", "llm", "jev"], default="off")
    ap.add_argument("--debug-hooks", action="store_true")
    args = ap.parse_args()
    base = SRC.read_text()
    base = set_value(base, "provider", "openai_compat", section="llm")
    for role, model in ROLES.items():
        base = set_value(base, role, model, section="llm.models.openai_compat")
    header = ("# GENERATED by research/paperb/make_flags_v3.py from config/flags.toml -- do not edit by hand.\n"
              "# Part D v3 (docs/specs/routing_docs_fixes.md): Part D's hosts; {arm}.\n")
    off = base
    on = base
    for key, value in FIXES_ON.items():
        on = set_value(on, key, value)
    for text_name, text in (("off", off), ("on", on)):
        if args.front_door != "off" or args.debug_hooks:
            for key, value in (("front_door", args.front_door if text_name == "on" else "off"),
                               ("debug_hooks", "on" if args.debug_hooks else "off")):
                text = set_value(text, key, value)
        arm = "every v3 fix at its shipped value" if text_name == "off" else "every v3 fix on"
        (OUT / f"flags_partd_v3_{text_name}.toml").write_text(header.format(arm=arm) + text)
    print("wrote flags_partd_v3_off.toml and flags_partd_v3_on.toml")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
